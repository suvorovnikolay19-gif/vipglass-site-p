import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
import {nodesByPath} from './dist/catalog-tree.mjs';
import {resourceByPath,hardware,hardwareTypePages,hardwareApplications,resourceMediaForNode} from './dist/resource-catalog.mjs';

// Compile only reviewed per-page manifests; a family fallback never qualifies.
const root=path.dirname(fileURLToPath(import.meta.url));
const manifests=fs.readdirSync(path.join(root,'docs')).filter(name=>/^exact-showers-(?:swing|sliding|branches)\.json$/.test(name)).sort();
const records={}, hashes=new Set();
for(const name of manifests) {
  const manifest=JSON.parse(fs.readFileSync(path.join(root,'docs',name),'utf8'));
  for(const asset of manifest.assets) {
    assert(nodesByPath.get(asset.path)?.path===asset.path,`Not a canonical catalogue page: ${asset.path}`);
    assert(!records[asset.path],`Repeated exact image for ${asset.path}`);
    assert(/^visual.*verified$/.test(asset.reviewStatus),`Visual review missing for ${asset.path}`);
    assert(Array.isArray(asset.verifiedVisibleProperties)&&asset.verifiedVisibleProperties.length,`No visual review findings: ${asset.path}`);
    for(const src of [asset.src,asset.thumb])assert(/^\/assets\/exact\/[a-z0-9-]+\/[a-z0-9-]+\.webp$/.test(src),`Unsafe exact asset path: ${src}`);
    const original=fs.readFileSync(path.join(root,'dist',asset.src));
    assert(original.length>1000&&fs.statSync(path.join(root,'dist',asset.thumb)).size>1000,`Empty media: ${asset.path}`);
    const hash=createHash('sha256').update(original).digest('hex');
    assert(!hashes.has(hash),`Reused original image: ${asset.path}`);hashes.add(hash);
    records[asset.path]={src:'.'+asset.src,thumbnail:'.'+asset.thumb,alt:asset.alt,
      caption:asset.alt+' · визуализация выбранной конфигурации',reviewStatus:asset.reviewStatus};
  }
}
fs.writeFileSync(path.join(root,'dist/exact-catalog-media.mjs'),
  '// Generated by sync-exact-media.mjs from visually reviewed manifests in docs/.\n'+
  '// Exact images are matched by full canonical path, never by family inheritance.\n'+
  'export const exactCatalogMedia = '+JSON.stringify(records,null,2)+';\n');
const planPath=path.join(root,'docs/exact-image-plan.json');
const plan=JSON.parse(fs.readFileSync(planPath,'utf8'));
const hardwareNodes=new Map([
  ...hardware,...hardwareTypePages,...hardwareApplications.map(node=>({...node,path:'/hardware/'+node.id})),
].map(node=>[node.path,node]));
plan.jobs=plan.jobs.filter(job=>!job.kind.startsWith('hardware-')||hardwareNodes.has(job.path));
for(const job of plan.jobs)if(records[job.path]) {
  job.status='visual_verified';job.currentImage=records[job.path];
  job.completedFile='dist/'+records[job.path].src.slice(2);
  job.completedThumbnailFile='dist/'+records[job.path].thumbnail.slice(2);
}
for(const job of plan.jobs) {
  const node=hardwareNodes.get(job.path)||resourceByPath.get(job.path);
  if(node) {
    const media=resourceMediaForNode(node);
    job.currentImage={src:media.src,thumbnail:media.thumbnail,alt:media.alt,caption:media.caption,kind:media.kind};
    if(job.kind.startsWith('hardware-'))job.supplierImageVerified=['catalog-photo','supplier-catalogue'].includes(media.kind);
  }
}
plan.summary.total=plan.jobs.length;plan.summary.uniquePaths=new Set(plan.jobs.map(job=>job.path)).size;
plan.summary.uniqueNewFiles=new Set(plan.jobs.map(job=>job.newFile)).size;
plan.summary.byStatus={};plan.summary.byCategory={};plan.summary.byKind={};
for(const job of plan.jobs) {
  plan.summary.byStatus[job.status]=(plan.summary.byStatus[job.status]||0)+1;
  const category=plan.summary.byCategory[job.category]||={total:0,pending:0,requires_verified_supplier_photo:0,visual_verified:0};
  category.total++;
  if(['pending','requires_verified_supplier_photo','visual_verified'].includes(job.status))category[job.status]++;
  plan.summary.byKind[job.kind]=(plan.summary.byKind[job.kind]||0)+1;
}
fs.writeFileSync(planPath,JSON.stringify(plan,null,2)+'\n');
console.log(JSON.stringify({reviewedExactPaths:Object.keys(records).length,manifests,remaining:plan.summary.byStatus},null,2));
