import assert from 'node:assert/strict';
import {createProjectMap} from './dist/project-map.mjs';
import {portfolioExamples} from './dist/portfolio-data.mjs';
const esc=s=>String(s??'').replaceAll('"','&quot;').replaceAll('<','&lt;');
const ui=createProjectMap({esc,btn:(t,u)=>`<a href="${u}">${t}</a>`,crumb:()=>'<nav>Главная</nav>'});
const html=ui.page();
assert.equal((html.match(/<h1>/g)||[]).length,1);
assert.equal((html.match(/data-map-project=/g)||[]).length,6);
assert.match(html,/Схема и расположение точек условные/);
assert.match(html,/aria-pressed="true"/);
const buttons=portfolioExamples.map(p=>({dataset:{mapProject:p.id},classList:{toggle(){}},setAttribute(k,v){this[k]=v;}}));
const values={},plane={style:{setProperty(k,v){values[k]=v;}}};
const popover={innerHTML:'',offsetWidth:100,style:{},classList:{remove(){},add(){}}};
let click;
const scope={querySelectorAll:()=>buttons,addEventListener(t,handler){if(t==='click')click=handler;}};
const viewport={dataset:{},closest:()=>scope,querySelector:s=>s==='.pm-map-plane'?plane:popover};
ui.bind({querySelectorAll:()=>[viewport]});
click({target:{closest:s=>s.includes('data-map-project')?{dataset:{mapProject:portfolioExamples[3].id}}:null}});
assert.match(popover.innerHTML,new RegExp('/portfolio/'+portfolioExamples[3].id));
assert.equal(buttons[3]['aria-pressed'],'true');
assert.equal(buttons[0]['aria-pressed'],'false');
const zoom=mode=>click({target:{closest:s=>s==='[data-map-zoom]'?{dataset:{mapZoom:mode}}:null}});
for(let i=0;i<20;i++)zoom('in');assert.equal(values['--map-zoom'],1.8);
for(let i=0;i<20;i++)zoom('out');assert.equal(values['--map-zoom'],.8);
zoom('reset');assert.equal(values['--map-zoom'],1);
ui.bind({querySelectorAll:()=>[viewport]});assert.equal(viewport.dataset.bound,'1');
console.log('Map: 6 points, project reveal, selection state, bounded zoom and reset passed.');
